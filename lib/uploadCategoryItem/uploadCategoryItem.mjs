import mysql from "mysql2"

// define OUTSIDE so it closes automatically
const pool = mysql.createPool({
  host: process.env.RDS_HOST,
  user: process.env.RDS_USER,
  password: process.env.RDS_PASSWORD,
  database: process.env.RDS_DATABASE,
})

export const handler = async (event) => {
  let result
  let code

  try {
    // API Gateway sends the JSON as a string in event.body
    const body = typeof event.body === "string" ? JSON.parse(event.body) : event

    // Validate input
    if (!Array.isArray(body.items)) {
      //make sure the input is an array
      throw new Error("'items' must be an array")
    }

    const items = body.items

    // Get the categories for the requested names
    const getCategories = (names) => {
      return new Promise((resolve, reject) => {
        const catQuery =
          "SELECT cat_id, cat_name FROM Category WHERE cat_name IN (?)"
        pool.query(catQuery, [names], (error, rows) => {
          if (error) {
            reject(new Error("Database error: " + error.sqlMessage))
          } else {
            resolve(rows || [])
          }
        })
      })
    }

    // Insert new items (item_id is generated by the database)
    const insertItems = (rows) => {
      return new Promise((resolve, reject) => {
        const insertQuery =
          "INSERT INTO Item (item_name, item_lowlimit, item_highlimit, cat_id) VALUES ?"
        pool.query(insertQuery, [rows], (error, insertResult) => {
          if (error) {
            reject(new Error("Database error: " + error.sqlMessage))
          } else {
            resolve(insertResult)
          }
        })
      })
    }

    let newIds = []

    // Check that every category exists
    if (items.length > 0) {
      const names = [...new Set(items.map((item) => item.category))]
      const categories = await getCategories(names)

      const catIds = new Map()
      categories.forEach((c) => catIds.set(c.cat_name, c.cat_id))

      if (names.some((n) => !catIds.has(n))) {
        throw new Error("One or more categories does not exist")
      }

      // Save all items in one statement (all or nothing)
      const rows = items.map((item) => [
        item.name,
        item.lowLimit,
        item.highLimit,
        catIds.get(item.category),
      ])
      const insertResult = await insertItems(rows)

      // insertId is the ID of the first new row; the rest follow in order
      newIds = items.map((item, index) => insertResult.insertId + index)
    }

    result = {
      items: items.map((item, index) => ({
        category: item.category,
        itemID: newIds[index],
        name: item.name,
        highPrice: item.highLimit,
        lowPrice: item.lowLimit,
      })),
    }
    code = 200
  } catch (error) {
    result = { error: error.message }
    code = 400
  }

  const response = {
    statusCode: code,
    headers: { "Access-Control-Allow-Origin": "*" },
    body: JSON.stringify(result),
  }

  return response
}